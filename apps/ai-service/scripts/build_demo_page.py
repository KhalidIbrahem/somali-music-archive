# ------------------------------------------------------------------ inputs

def strip_credit(caption: str) -> str:
    return re.sub(r",\s*performed by .*$", "", caption).strip()


def read_captions(d: Path) -> dict[int, str]:
    out: dict[int, str] = {}
    for line in (d / "CAPTIONS.txt").read_text().splitlines():
        m = re.match(r"pair(\d{3}):\s*(.*)", line)
        if m:
            out[int(m.group(1))] = m.group(2).strip()
    return out


def pcs_csv(name: str) -> dict[int, dict]:
    out: dict[int, dict] = {}
    with (DATA / "eval_pcs" / f"{name}.csv").open() as fh:
        for row in csv.DictReader(fh):
            m = re.search(r"(?:pair|gen_)(\d{3})", row.get("clip", ""))
            if m:
                out[int(m.group(1))] = row
    return out


def num(x) -> float | None:
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def load_scale(tag: str) -> dict:
    e = json.loads((RUNS / f"qaraami_{tag}_r32" / f"eval_{tag}.json").read_text())
    cfg = json.loads((RUNS / f"qaraami_{tag}_r32" / "config.json").read_text())
    steps, vals = [], []
    with (RUNS / f"qaraami_{tag}_r32" / "loss.csv").open() as fh:
        for row in csv.DictReader(fh):
            if row["val_loss"]:
                steps.append(int(row["step"]))
                vals.append(float(row["val_loss"]))
    return {"eval": e, "cfg": cfg, "val_curve": (steps, vals)}


def split_counts() -> dict:
    clips: dict[str, int] = {}
    songs: dict[str, set] = {}
    for line in (DATA / "scale_captions.jsonl").open():
        d = json.loads(line)
        clips[d["split"]] = clips.get(d["split"], 0) + 1
        songs.setdefault(d["split"], set()).add(d["song_sha256"])
    all_songs = set().union(*songs.values())
    return {"clips": clips, "songs": {k: len(v) for k, v in songs.items()},
            "total_clips": sum(clips.values()), "total_songs": len(all_songs)}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


def listening_results() -> dict[str, dict]:
    """Latest blind paired-comparison result per set, from data/listening/*.json."""
    out: dict[str, dict] = {}
    if not LISTENING.is_dir():
        return out
    for p in sorted(LISTENING.glob("*.json")):
        r = json.loads(p.read_text())
        s = r.get("summary") or {}
        if r.get("set") and s.get("n"):
            out[r["set"]] = {"file": p.name, "listener": r.get("listener", ""), "date": r.get("date", ""),
                             "n": s["n"], "adapter": s["adapter"], "base": s["base"], "none": s["none"]}
    return out


# ---------------------------------------------------------------- transcode

def transcode(clips: list[Clip]) -> None:
    AUDIO.mkdir(parents=True, exist_ok=True)
    for c in clips:
        dst = AUDIO / f"{c.name}.mp3"
        if dst.exists() and dst.stat().st_mtime >= c.src.stat().st_mtime:
            continue
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-i", str(c.src), "-ac", "1", "-ar", "32000",
             "-codec:a", "libmp3lame", "-b:a", f"{MP3_KBPS}k", "-id3v2_version", "0", str(dst)],
            check=True)


