"""Build the shareable QaraamiGen demo page from the run artifacts on disk.

A plain academic page in the style of a research group's demo index: prose,
tables, figures and inline audio players, base model against adapter on the
same prompt and seed. Every number comes from the eval JSON, run configs and
scorer CSVs; every clip is model output already generated by the evaluation
scripts. Nothing is generated or scored here, so the page cannot disagree with
the reports.

Outputs (docs/demo/site/):
  index.html            relative links into audio/ and figures/  (tracked)
  audio/*.mp3           transcoded from the A/B wavs, 96 kb/s mono  (ignored)
  figures/*.png         copied from docs/figures                    (ignored)
  QaraamiGen-demo.html  single self-contained file, audio and figures
                        inlined as data URIs; the thing to send      (ignored)

Also writes docs/figures/ft7_scale_val_curves.{png,svg} (validation CE per
checkpoint for the medium and large runs, from runs/qaraami_*_r32/loss.csv).

Clip selection is fixed by rule, not by ear: the four synthetic qaraami prompts
and the first four catalogue prompts of the 16-prompt scale A/B set; the first
four pairs of each small-model set; the three melody-conditioned clips with the
highest voiced fraction; the large run's per-checkpoint sample at steps 250,
1000, 2000 and the best checkpoint. Catalogue prompts carry performer credits
from the Harvard finding aid; those are omitted from the displayed captions.

Blind listening results, if any exist in data/listening/ (written by
ab_listen.py's paired-comparison test), are summarised in the Results section;
until then the page says the study is pending.

Usage (from the repo root, the musicgen env has matplotlib):
  ~/ai/musicgen-env/bin/python apps/ai-service/scripts/build_demo_page.py
"""
