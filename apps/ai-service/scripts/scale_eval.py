"""Evaluate a scaled MusicGen adapter against its own base (Stage 2-4).

Three parts, all song-level and rights-safe (no source audio leaves the machine;
only generated clips are written):

1. Per-SONG held-out test cross-entropy, base vs adapter, with a bootstrap 95%
   CI over songs. Clips are grouped by song_sha256, averaged within a song, and
   the CI is resampled over songs (the independent unit), not clips — so the
   interval is honest about how few songs the test split has.

2. A 16-clip A/B set into data/ab_<tag>/: the same 16 seeded test captions
   generated by base and by the adapter with identical seeds, plus PCS +
   trackable-melody (voiced fraction) for every clip. The caption list is fixed
   across models (--ab-captions, written once from the test split when the file
   does not exist; --ab-rights restricts the seeding to rows with those rights)
   so every model is heard on the same prompts.

3. A summary JSON runs/<run>/eval_<tag>.json with base/adapter test CE + CI,
   mean trackable-melody and PCS for base vs adapter, the per-caption table,
   the test rows per source and the pinned scorer version (torchcrepe, PCS
   hop / confidence gate, sha256 of scripts/pcs.py).

Stage 3-4 extensions:
  * captions rows may carry "tokens_dir" / "chroma_dir" (repo-relative); they win
    over the CLI --tokens-dir / --chroma-dir, exactly as in scale_train
  * musicgen-melody: the per-song CE passes each clip's chroma as input_features,
    and every A/B pair conditions base AND adapter on the SAME reference chroma.
    The references come from --melody-refs <dir of wav> (default: the run
    captions' ahmed_oud test clips) spread over SONGS: pair i takes song i mod k
    (build_sets stems are <set>_<sha12>_segNNN, so the song is the stem without
    its segment), so sixteen pairs never sit on one song's sixteen segments; the
    reference file name and song are saved per pair
  * --headtohead-run <other run dir>: after the main eval, the other run's best
    adapter is loaded on the same base and scored on the SAME test rows, which
    are restricted to the sources both runs trained on (read from the other
    run's config.json -> captions), so a combined run is compared with an
    Ahmed-only run on the Ahmed songs, not on the Harvard songs it alone saw.
    The paired per-song difference (other − this, positive = this adapter has
    the lower CE) with a bootstrap 95% CI, overall and per source, lands in
    result["headtohead"]

Everything that can fail is checked before any model is loaded: an empty test
split, a run without a saved adapter, a head-to-head run without one, on a
different base model or without a shared source, a rights filter that leaves
no caption to seed from. The eval JSON is written only once everything asked
for has been computed, so an existing eval_<tag>.json is a complete one.

Generation is always batch 1.

Usage (from apps/ai-service):
  python -m scripts.scale_eval --run runs/qaraami_medium_r32 --model facebook/musicgen-medium \
     --captions ../../data/scale_captions.jsonl --tokens-dir ../../data/scale_tokens \
     --tag medium --n-ab 16
  python -m scripts.scale_eval --run runs/combined_large --model facebook/musicgen-large \
     --captions ../../data/sets/run_combined_large_captions.jsonl --tag combined_large \
     --n-ab 16 --ab-seconds 30 --ab-captions data/ab_captions_ahmed.json \
     --ab-rights ahmed_ilkacase_consented --headtohead-run runs/ahmed_only_large
  python -m scripts.scale_eval --run runs/ahmed_melody --model facebook/musicgen-melody \
     --captions ../../data/sets/ahmed_oud/captions.jsonl --tag ahmed_melody \
     --ab-captions data/ab_captions_ahmed.json --ab-rights ahmed_ilkacase_consented \
     --melody-refs data/sets/ahmed_oud/clips/test
"""
