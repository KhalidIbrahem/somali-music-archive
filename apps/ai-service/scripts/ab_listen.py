@dataclass
class Clip:
    file: str
    pcs: float | None = None
    voiced: float | None = None
    tonic: str | None = None
    tuning: float | None = None


@dataclass
class Pair:
    index: int
    caption: str
    base: Clip | None = None
    adapter: Clip | None = None


@dataclass
class ListeningSet:
    name: str          # URL segment and directory name under data/
    title: str
    dir: Path
    note: str = ""
    pairs: list[Pair] = field(default_factory=list)
    summary: dict = field(default_factory=dict)

    @property
    def testable(self) -> bool:
        return any(p.base and p.adapter for p in self.pairs)


def read_captions(d: Path) -> dict[int, str]:
    out: dict[int, str] = {}
    p = d / "CAPTIONS.txt"
    if not p.exists():
        return out
    for line in p.read_text().splitlines():
        m = re.match(r"pair(\d{3}):\s*(.*)", line)
        if m:
            out[int(m.group(1))] = m.group(2).strip()
    return out


def scan_pairs(d: Path) -> dict[int, Pair]:
    captions = read_captions(d)
    pairs: dict[int, Pair] = {}
    for f in sorted(d.glob("pair*.wav")):
        m = PAIR.search(f.name)
        if not m:
            continue
        i = int(m.group(1))
        pair = pairs.setdefault(i, Pair(i, captions.get(i, "")))
        clip = Clip(f.name)
        if m.group(2) == "base":
            pair.base = clip
        else:
            pair.adapter = clip
    return pairs


def scale_set(tag: str) -> ListeningSet | None:
    d = DATA / f"ab_{tag}"
    ev = RUNS / f"qaraami_{tag}_r32" / f"eval_{tag}.json"
    if not d.is_dir():
        return None
    s = ListeningSet(f"ab_{tag}", f"MusicGen-{tag}", d)
    pairs = scan_pairs(d)
    if ev.exists():
        e = json.loads(ev.read_text())
        ce = e["per_song_ce"]
        imp = ce["improvement_base_minus_adapter"]
        s.summary = {
            "model": e["model"],
            "best_ckpt": e["best_ckpt"],
            "songs": ce["n_songs"],
            "ce_base": ce["base"]["mean"],
            "ce_adapter": ce["adapter"]["mean"],
            "ce_gain": imp["mean"],
            "ce_ci": imp["ci95"],
            "significant": imp["significant"],
            "pcs_base": e["ab"]["base"]["pcs_mean"],
            "pcs_adapter": e["ab"]["adapter"]["pcs_mean"],
            "voiced_base": e["ab"]["base"]["voiced_fraction_mean"],
            "voiced_adapter": e["ab"]["adapter"]["voiced_fraction_mean"],
        }
        for row in e["ab"]["pairs"]:
            pair = pairs.get(row["pair"])
            if pair is None:
                continue
            if not pair.caption:
                pair.caption = row.get("caption", "")
            for side in ("base", "adapter"):
                clip = getattr(pair, side)
                sc = row.get(side) or {}
                if clip and sc.get("scored"):
                    clip.pcs = sc.get("pcs")
                    clip.voiced = sc.get("voiced_fraction")
                    clip.tonic = sc.get("tonic")
                    clip.tuning = sc.get("tuning_offset_cents")
        s.note = f"{e['model']}, best checkpoint {e['best_ckpt']}; same 16 captions and seeds as every other scale set."
    s.pairs = [pairs[i] for i in sorted(pairs)]
    return s


def pcs_csv(name: str) -> dict[int, dict]:
    """Per-clip scores from data/eval_pcs/<name>.csv keyed by pair index.

    The scorer names clips gen_NNN in the order they were generated, which is
    the pair order of the listening set; pairNNN is accepted too.
    """
    p = DATA / "eval_pcs" / f"{name}.csv"
    out: dict[int, dict] = {}
    if not p.exists():
        return out
    with p.open() as fh:
        for row in csv.DictReader(fh):
            m = re.search(r"(?:pair|gen_)(\d{3})", str(row.get("clip", "")))
            if m:
                out[int(m.group(1))] = row
    return out


def _num(row: dict, *keys: str) -> float | None:
    for k in keys:
        if k in row and row[k] not in ("", None):
            try:
                return float(row[k])
            except ValueError:
                pass
    return None


def legacy_set(name: str, title: str, base_group: str, ft_group: str, note: str) -> ListeningSet | None:
    d = DATA / name
    if not d.is_dir():
        return None
    s = ListeningSet(name, title, d, note)
    pairs = scan_pairs(d)
    for side, group in (("base", base_group), ("adapter", ft_group)):
        rows = pcs_csv(group)
        for i, row in rows.items():
            clip = getattr(pairs.get(i), side, None) if i in pairs else None
            if clip:
                clip.pcs = _num(row, "pcs", "pcs_score")
                clip.voiced = _num(row, "voiced_fraction", "voiced")
                clip.tonic = row.get("tonic") or None
                clip.tuning = _num(row, "tuning_offset_cents", "tuning_offset")
    for group, key in ((base_group, "base"), (ft_group, "adapter")):
        j = DATA / "eval_pcs" / f"{group}.json"
        if j.exists():
            g = json.loads(j.read_text())
            s.summary[f"pcs_{key}"] = g.get("pcs_mean")
            s.summary[f"voiced_{key}"] = g.get("voiced_fraction_mean")
    s.pairs = [pairs[i] for i in sorted(pairs)]
    return s


def melody_set() -> ListeningSet | None:
    d = DATA / "ab_melody"
    j = d / "melody_condition.json"
    if not d.is_dir():
        return None
    s = ListeningSet("ab_melody", "musicgen-melody, conditioned on real qaraami melodies", d)
    if j.exists():
        e = json.loads(j.read_text())
        s.note = (f"{e['model']}, no adapter, one caption: \"{e['caption']}\". "
                  f"Each clip follows the chroma of a held-out qaraami clip (named per row). "
                  f"Mean PCS {e['pcs_mean']:.3f}, voiced fraction {e['voiced_fraction_mean']:.3f}.")
        for c in e.get("clips", []):
            s.pairs.append(Pair(c["i"], f"melody from {c['ref']}",
                                base=Clip(c["file"], c.get("pcs"), c.get("voiced_fraction"))))
    else:
        for i, f in enumerate(sorted(d.glob("melody*_base.wav"))):
            s.pairs.append(Pair(i, "", base=Clip(f.name)))
    return s


def scored_set(d: Path) -> ListeningSet | None:
    """Any other data/ab_<name>/ with pairNNN_{base,adapter}.wav and an optional
    ab_scores.json (written by dpo_train.py: note + per-pair base/adapter terms)."""
    pairs = scan_pairs(d)
    if not pairs:
        return None
    s = ListeningSet(d.name, d.name.replace("_", " "), d)
    j = d / "ab_scores.json"
    if j.exists():
        e = json.loads(j.read_text())
        s.note = e.get("note", "")
        for row in e.get("pairs", []):
            pair = pairs.get(row["pair"])
            if pair is None:
                continue
            if not pair.caption:
                pair.caption = row.get("caption", "")
            for side in ("base", "adapter"):
                clip, sc = getattr(pair, side), row.get(side) or {}
                if clip and sc.get("pcs") is not None:
                    clip.pcs, clip.voiced = sc.get("pcs"), sc.get("voiced_fraction")
    readme = d / "README.txt"
    if readme.exists():
        s.note = (s.note + " " + readme.read_text().strip()).strip()
    s.pairs = [pairs[i] for i in sorted(pairs)]
    return s


def load_sets() -> list[ListeningSet]:
    sets: list[ListeningSet] = []
    for tag in ("medium", "large"):
        s = scale_set(tag)
        if s:
            sets.append(s)
    known = {"ab_medium", "ab_large", "ab_melody"}
    for d in sorted(DATA.glob("ab_*")):
        if d.is_dir() and d.name not in known:
            s = scored_set(d)
            if s:
                sets.append(s)
    s = legacy_set("oud_ab_listening", "MusicGen-small, oud adapter (step 500)", "oud_base", "oud_lora500",
                   "8 seeded oud captions, base vs the oud adapter; 10 s clips.")
    if s:
        sets.append(s)
    s = legacy_set("harvard_ab_listening", "MusicGen-small, harvard_raw adapter (step 1500)", "harvard_base",
                   "harvard_lora1500", "8 seeded Harvard test captions, base vs the harvard_raw adapter; 10 s clips.")
    if s:
        sets.append(s)
    s = melody_set()
    if s:
        sets.append(s)
    return sets


