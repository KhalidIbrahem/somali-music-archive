REPO = Path(__file__).resolve().parents[3]
N_TEST_CLIPS = 128
DEFAULT_AB_CAPTIONS = "data/ab_captions.json"
MELODY_REF_SET = "ahmed_oud"  # default reference chroma: this set's test clips
SEG_RE = re.compile(r"_seg\d{3}$")  # build_sets / build_scale_dataset clip stems end in _segNNN


def resolve(path: str | Path) -> Path:
    """CLI paths are repo-relative unless absolute (as --run always was)."""
    p = Path(path)
    return p if p.is_absolute() else REPO / p


def resolve_captions_arg(cfg_path: str | None) -> Path | None:
    """A run's config.json stores --captions as given: absolute, relative to
    apps/ai-service (the scripts' cwd) or repo-relative."""
    if not cfg_path:
        return None
    p = Path(cfg_path)
    for cand in (p, REPO / "apps/ai-service" / p, REPO / p):
        if cand.exists():
            return cand
    return None


def source_of(row: dict) -> str:
    """The set a row belongs to; the older captions files carry "rights" only."""
    return row.get("source") or row.get("rights") or "unlabelled"


def select_test_rows(rows: list[dict], n: int = N_TEST_CLIPS) -> list[dict]:
    """The eval subset: sorted by clip_path, strided to at most n clips."""
    stride = max(1, len(rows) // n)
    return sorted(rows, key=lambda r: r["clip_path"])[::stride][:n]


def source_counts(rows: list[dict]) -> dict[str, dict[str, int]]:
    """{source: {"clips": n, "songs": n}} over the rows."""
    clips: dict[str, int] = {}
    songs: dict[str, set[str]] = {}
    for r in rows:
        src = source_of(r)
        clips[src] = clips.get(src, 0) + 1
        songs.setdefault(src, set()).add(r["song_sha256"])
    return {src: {"clips": clips[src], "songs": len(songs[src])} for src in sorted(clips)}


def captions_sources(captions: Path) -> set[str]:
    """Every source named in a captions file (all splits)."""
    out: set[str] = set()
    with open(captions) as fh:
        for line in fh:
            line = line.strip()
            if line:
                out.add(source_of(json.loads(line)))
    return out


def per_song_ce(model, tok, rows, tokens_dir, melody: bool = False, chroma_dir=None) -> dict[str, float]:
    """Mean token CE per song_sha256 over its clips (eval mode). A melody model
    gets each clip's chroma as input_features, through scale_train.micro_step."""
    by_song: dict[str, list[float]] = {}
    model.eval()
    with torch.no_grad():
        for r in rows:
            loss = micro_step(model, tok, r, tokens_dir, melody, chroma_dir)
            by_song.setdefault(r["song_sha256"], []).append(loss.item())
    if DEVICE == "mps":
        torch.mps.empty_cache()
    return {s: float(np.mean(v)) for s, v in by_song.items()}


def bootstrap_ci(values: list[float], n: int = 2000, seed: int = 0) -> tuple[float, float, float]:
    """Mean and percentile bootstrap 95% CI; an empty list is an error, never NaN."""
    if len(values) == 0:
        raise ValueError("bootstrap_ci: no values (empty test split?)")
    rng = random.Random(seed)
    arr = np.array(values)
    means = [float(np.mean([arr[rng.randrange(len(arr))] for _ in arr])) for _ in range(n)]
    return float(np.mean(arr)), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def headtohead_stats(this_song: dict[str, float], other_song: dict[str, float], n_boot: int = 2000, seed: int = 0) -> dict:
    """Paired per-song comparison of two adapters scored on the same test songs.
    difference = other − this per song (positive: this adapter has the lower CE),
    with a bootstrap 95% CI over songs; significant when the CI excludes zero
    and there are at least two songs (one song has no variance to resample: its
    CI collapses on the point and says nothing)."""
    songs = sorted(set(this_song) & set(other_song))
    if not songs:
        raise ValueError("head-to-head: no song is scored by both adapters")
    t_mean, t_lo, t_hi = bootstrap_ci([this_song[s] for s in songs], n_boot, seed)
    o_mean, o_lo, o_hi = bootstrap_ci([other_song[s] for s in songs], n_boot, seed)
    d_mean, d_lo, d_hi = bootstrap_ci([other_song[s] - this_song[s] for s in songs], n_boot, seed)
    return {
        "n_songs": len(songs),
        "this": {"mean": round(t_mean, 4), "ci95": [round(t_lo, 4), round(t_hi, 4)]},
        "other": {"mean": round(o_mean, 4), "ci95": [round(o_lo, 4), round(o_hi, 4)]},
        "difference_other_minus_this": {"mean": round(d_mean, 4), "ci95": [round(d_lo, 4), round(d_hi, 4)],
                                        "significant": bool(len(songs) >= 2 and (d_lo > 0 or d_hi < 0))},
    }


def per_source_headtohead(this_song: dict[str, float], other_song: dict[str, float], song_source: dict[str, str],
                          n_boot: int = 2000, seed: int = 0) -> dict[str, dict]:
    """headtohead_stats per source, over the songs both adapters scored; a source
    with a single song still gets a row (its CI collapses on the one value)."""
    out: dict[str, dict] = {}
    for src in sorted(set(song_source.values())):
        t = {s: v for s, v in this_song.items() if song_source.get(s) == src}
        o = {s: v for s, v in other_song.items() if song_source.get(s) == src}
        if set(t) & set(o):
            out[src] = headtohead_stats(t, o, n_boot, seed)
    return out


def scorer_version() -> dict:
    """Pin of the melody scorer: torchcrepe version, PCS hop and confidence gate,
    and the sha256 of scripts/pcs.py itself."""
    try:
        crepe = version("torchcrepe")
    except PackageNotFoundError:
        crepe = "not installed"
    src = Path(pcs_module.__file__).read_bytes()
    return {"torchcrepe": crepe, "pcs_hop": pcs_module.HOP, "pcs_conf_thresh": pcs_module.CONF_THRESH,
            "pcs_file_sha256": hashlib.sha256(src).hexdigest()}


def score_clip(path: Path) -> dict:
    audio, sr = sf.read(path, dtype="float32")
    if audio.ndim > 1:
        audio = audio.mean(axis=1)
    f0, pd = extract_f0(audio, DEVICE, sr=sr)
    res = score_frames(f0, pd)
    if DEVICE == "mps":
        torch.mps.empty_cache()
    if res is None:
        return {"scored": False}
    return {"scored": True, "pcs": round(res.pcs, 4), "voiced_fraction": round(res.voiced_fraction, 3),
            "tuning_offset_cents": round(res.tuning_offset_cents, 1), "tonic": res.tonic_name}


def load_wav_mono(path: Path) -> tuple[np.ndarray, int]:
    audio, sr = sf.read(path, dtype="float32")
    if audio.ndim > 1:
        audio = audio.mean(axis=1)
    return audio, int(sr)


@torch.no_grad()
def generate(model, processor, caption, seconds, seed, out_path, ref_audio: np.ndarray | None = None, ref_sr: int = 32000) -> float:
    """Batch-1 generation. With ref_audio (melody model) the processor extracts the
    conditioning chroma from it, so base and adapter share the same reference."""
    model.eval()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    torch.manual_seed(seed)
    if ref_audio is not None:
        inputs = processor(audio=ref_audio, sampling_rate=ref_sr, text=[caption], padding=True, return_tensors="pt").to(DEVICE)
    else:
        inputs = processor(text=[caption], padding=True, return_tensors="pt").to(DEVICE)
    t0 = time.time()
    audio = model.generate(**inputs, do_sample=True, guidance_scale=3.0, max_new_tokens=int(seconds * 50))
    sr = model.config.audio_encoder.sampling_rate
    sf.write(out_path, audio[0].cpu().numpy().squeeze(), sr, subtype="PCM_16")
    if DEVICE == "mps":
        torch.mps.empty_cache()
    return time.time() - t0


def ab_captions(captions: Path, n: int, cache: Path | None = None, seed: int = 42,
                rights: list[str] | None = None) -> list[str]:
    """The fixed A/B caption list: read from `cache` when it exists, otherwise n
    seeded test captions sampled from the run captions and written there. With
    `rights`, only test rows carrying one of those rights may seed the list (an
    Ahmed cache must never be seeded from Harvard captions); no such row is an
    error, never a silent fallback."""
    cache = cache if cache is not None else REPO / DEFAULT_AB_CAPTIONS
    if cache.exists():
        return json.loads(cache.read_text())[:n]
    test = load_split(captions, "test")
    if rights:
        test = [r for r in test if r.get("rights") in set(rights)]
        if not test:
            raise SystemExit(f"--ab-rights {sorted(rights)}: no test row of {captions} carries these rights; "
                             f"refusing to seed {cache}")
    uniq = sorted({r["caption"] for r in test})
    if not uniq:
        raise SystemExit(f"no test captions in {captions} to seed {cache} from")
    picked = random.Random(seed).sample(uniq, min(n, len(uniq)))
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps(picked, indent=2))
    return picked


def song_key(path: Path) -> str:
    """The song a clip belongs to, from its stem: <set>_<sha12>_segNNN -> <set>_<sha12>."""
    return SEG_RE.sub("", path.stem)


def spread_over_songs(by_song: dict[str, list[Path]], n: int) -> list[tuple[str, Path]]:
    """n (song, clip) references round-robin over the sorted songs: reference i
    is song i mod k, taking that song's (i div k)-th clip, so every song is heard
    before any song repeats and a clip only repeats once the songs run out of
    clips."""
    songs = sorted(s for s, clips in by_song.items() if clips)
    if not songs:
        return []
    out = []
    for i in range(n):
        song = songs[i % len(songs)]
        clips = sorted(by_song[song])
        out.append((song, clips[(i // len(songs)) % len(clips)]))
    return out


def melody_reference_clips(captions: Path, refs_dir: Path | None, n: int) -> list[tuple[str, Path]]:
    """(song, clip) references whose chroma conditions both sides of each A/B
    pair, spread over songs: --melody-refs <dir> (wavs grouped by song_key), else
    the run captions' ahmed_oud test clips (grouped by song_sha256)."""
    by_song: dict[str, list[Path]] = {}
    if refs_dir is not None:
        for p in sorted(refs_dir.glob("*.wav")):
            by_song.setdefault(song_key(p), []).append(p)
        if not by_song:
            raise FileNotFoundError(f"--melody-refs {refs_dir}: no .wav files")
    else:
        for r in load_split(captions, "test"):
            if r.get("source") == MELODY_REF_SET:
                by_song.setdefault(r["song_sha256"], []).append(resolve(r["clip_path"]))
        if not by_song:
            raise FileNotFoundError(f"no {MELODY_REF_SET} test clips in {captions}; pass --melody-refs <dir of wav>")
    return spread_over_songs(by_song, n)


def find_best_ckpt(run: Path) -> Path:
    """Best SAVED checkpoint by val CE: only loss.csv val rows whose
    ckpt_step_NNNN directory exists count (the always-validated step 100 has no
    checkpoint and must not win); fallback the last checkpoint dir, and the run
    dir itself when it holds none (callers check with require_adapter)."""
    ckpts: dict[int, Path] = {}
    for p in run.glob("ckpt_step_*"):
        try:
            ckpts[int(p.name.split("_")[-1])] = p
        except ValueError:
            continue
    best_step, best_val = None, float("inf")
    lc = run / "loss.csv"
    if lc.exists():
        with open(lc) as fh:
            for row in csv.DictReader(fh):
                if not row.get("val_loss"):
                    continue
                try:
                    step, v = int(row["step"]), float(row["val_loss"])
                except (KeyError, ValueError):
                    continue
                if step in ckpts and v < best_val:
                    best_val, best_step = v, step
    if best_step is not None:
        return ckpts[best_step]
    return ckpts[max(ckpts)] if ckpts else run


def require_adapter(ckpt: Path, what: str) -> Path:
    """A LoRA checkpoint directory (adapter_config.json present), or SystemExit."""
    if not (ckpt / "adapter_config.json").exists():
        raise SystemExit(f"{what}: {ckpt} holds no LoRA adapter (adapter_config.json missing)")
    return ckpt


def plan_headtohead(captions: Path, other_run: Path, model: str, test: list[dict], n: int = N_TEST_CLIPS) -> dict:
    """Everything the head-to-head needs, checked before any model is loaded:
    the other run's best adapter, its base model (config.json) equal to ours,
    the sources both runs' captions share, and this run's test rows restricted
    to those sources (same sort / stride / cap as the main eval)."""
    if not other_run.is_dir():
        raise SystemExit(f"--headtohead-run {other_run}: not a run directory")
    other_ckpt = require_adapter(find_best_ckpt(other_run), f"--headtohead-run {other_run}")
    cfg_path = other_run / "config.json"
    if not cfg_path.exists():
        raise SystemExit(f"--headtohead-run {other_run}: no config.json (cannot check its base model and captions)")
    cfg = json.loads(cfg_path.read_text())
    if cfg.get("model") != model:
        raise SystemExit(f"--headtohead-run {other_run}: trained on {cfg.get('model')!r}, this eval is on {model!r}")
    other_captions = resolve_captions_arg(cfg.get("captions"))
    if other_captions is None:
        raise SystemExit(f"--headtohead-run {other_run}: its captions file {cfg.get('captions')!r} is missing")
    shared = captions_sources(captions) & captions_sources(other_captions)
    if not shared:
        raise SystemExit(f"--headtohead-run {other_run}: no source in common between {captions} and {other_captions}")
    rows = select_test_rows([r for r in test if source_of(r) in shared], n)
    if not rows:
        raise SystemExit(f"--headtohead-run {other_run}: no test row of {captions} in the shared sources {sorted(shared)}")
    return {"other_run": other_run, "other_ckpt": other_ckpt, "other_captions": other_captions,
            "shared_sources": sorted(shared), "rows": rows}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--model", required=True)
    ap.add_argument("--captions", required=True)
    ap.add_argument("--tokens-dir", default=None, help="fallback for rows without their own tokens_dir")
    ap.add_argument("--chroma-dir", default=None, help="musicgen-melody: fallback for rows without their own chroma_dir")
    ap.add_argument("--tag", required=True)
    ap.add_argument("--rank", type=int, default=32)
    ap.add_argument("--alpha", type=int, default=64)
    ap.add_argument("--targets", nargs="*", default=["q_proj", "k_proj", "v_proj", "out_proj", "fc1", "fc2"])
    ap.add_argument("--n-ab", type=int, default=16)
    ap.add_argument("--ab-seconds", type=int, default=15)
    ap.add_argument("--ab-captions", default=DEFAULT_AB_CAPTIONS, help="fixed caption list (json), repo-relative")
    ap.add_argument("--ab-rights", nargs="*", default=None,
                    help="seed a new --ab-captions list from test rows with these rights only (needs an explicit --ab-captions)")
    ap.add_argument("--melody-refs", default=None, help="musicgen-melody: dir of reference wavs for the A/B chroma")
    ap.add_argument("--headtohead-run", default=None, help="other run dir: paired per-song CE against its best adapter")
    args = ap.parse_args()
    run = resolve(args.run)
    captions = Path(args.captions)
    tokens_dir = Path(args.tokens_dir) if args.tokens_dir else None
    chroma_dir = Path(args.chroma_dir) if args.chroma_dir else None
    melody = is_melody(args.model)

    # --- everything that can fail, before any model is loaded ----------------------
    test = load_split(captions, "test")
    if not test:
        raise SystemExit(f"no test rows in {captions}")
    test_rows = select_test_rows(test)
    if melody:
        missing = [r["clip_path"] for r in test_rows if (chroma_path(chroma_dir, r) is None or not chroma_path(chroma_dir, r).exists())]
        if missing:
            raise FileNotFoundError(f"melody eval: {len(missing)} test rows without chroma, e.g. {missing[0]}")
    ckpt = require_adapter(find_best_ckpt(run), f"--run {run}")
    h2h = plan_headtohead(captions, resolve(args.headtohead_run), args.model, test) if args.headtohead_run else None
    if args.ab_rights and args.ab_captions == DEFAULT_AB_CAPTIONS:
        raise SystemExit(f"--ab-rights needs an explicit --ab-captions file; the default {DEFAULT_AB_CAPTIONS} "
                         "holds the Harvard-era caption list")
    ab_cache = resolve(args.ab_captions)
    refs: list[tuple[str, Path]] = []
    if melody:
        refs = melody_reference_clips(captions, resolve(args.melody_refs) if args.melody_refs else None, args.n_ab)
    # the only write before the models load: seeding the caption cache, once every check above has passed
    caps = ab_captions(captions, args.n_ab, ab_cache, rights=args.ab_rights)
    refs = refs[:len(caps)] if refs else refs

    processor = AutoProcessor.from_pretrained(args.model)
    tok = processor.tokenizer
    result = {"tag": args.tag, "model": args.model, "run": str(run), "best_ckpt": ckpt.name,
              "test_clips": len(test_rows), "test_songs": len({r["song_sha256"] for r in test_rows}),
              "test_sources": source_counts(test_rows),
              "captions": str(captions), "scorer_version": scorer_version()}

    # 1. per-song CE, base then adapter
    base = build_model(args.model, args.targets, args.rank, args.alpha, None)
    base_song = per_song_ce(base, tok, test_rows, tokens_dir, melody, chroma_dir)
    del base
    if DEVICE == "mps":
        torch.mps.empty_cache()
    adapter = build_model(args.model, args.targets, args.rank, args.alpha, str(ckpt))
    adapter_song = per_song_ce(adapter, tok, test_rows, tokens_dir, melody, chroma_dir)

    songs = sorted(set(base_song) & set(adapter_song))
    b_mean, b_lo, b_hi = bootstrap_ci([base_song[s] for s in songs])
    a_mean, a_lo, a_hi = bootstrap_ci([adapter_song[s] for s in songs])
    deltas = [base_song[s] - adapter_song[s] for s in songs]
    d_mean, d_lo, d_hi = bootstrap_ci(deltas)
    result["per_song_ce"] = {
        "n_songs": len(songs),
        "base": {"mean": round(b_mean, 4), "ci95": [round(b_lo, 4), round(b_hi, 4)]},
        "adapter": {"mean": round(a_mean, 4), "ci95": [round(a_lo, 4), round(a_hi, 4)]},
        "improvement_base_minus_adapter": {"mean": round(d_mean, 4), "ci95": [round(d_lo, 4), round(d_hi, 4)],
                                            "significant": d_lo > 0},
    }
    print(json.dumps(result["per_song_ce"], indent=2), flush=True)

    # 2. A/B set (same captions/seeds for base and adapter; same reference chroma per pair for melody)
    result["ab_captions_file"] = str(ab_cache)
    if melody:
        result["melody_refs"] = {"dir": str(refs[0][1].parent), "files": [p.name for _, p in refs],
                                 "songs": [s for s, _ in refs], "n_songs": len({s for s, _ in refs})}
    ab_dir = REPO / f"data/ab_{args.tag}"
    ab_dir.mkdir(parents=True, exist_ok=True)
    (ab_dir / "CAPTIONS.txt").write_text("".join(f"pair{i:03d}: {c}\n" for i, c in enumerate(caps)))
    rows_ab = []
    for i, cap in enumerate(caps):
        seed = 42 + i
        bpath = ab_dir / f"pair{i:03d}_base.wav"
        apath = ab_dir / f"pair{i:03d}_adapter.wav"
        ref_audio, ref_sr, ref_name, ref_song = None, 32000, None, None
        if melody:
            ref_song, ref = refs[i % len(refs)]
            ref_audio, ref_sr = load_wav_mono(ref)
            ref_name = ref.name
        # base first (adapter disabled in place; same reference chroma and seed as the adapter side)
        adapter.set_adapter(adapter.active_adapters[0]) if hasattr(adapter, "active_adapters") else None
        with adapter.disable_adapter():
            generate(adapter, processor, cap, args.ab_seconds, seed, bpath, ref_audio, ref_sr)
        generate(adapter, processor, cap, args.ab_seconds, seed, apath, ref_audio, ref_sr)
        sb, sa = score_clip(bpath), score_clip(apath)
        row = {"pair": i, "caption": cap, "base": sb, "adapter": sa}
        if ref_name is not None:
            row["melody_ref"] = ref_name
            row["melody_ref_song"] = ref_song
        rows_ab.append(row)
        print(f"  ab {i+1}/{len(caps)} base pcs/voiced={sb.get('pcs')}/{sb.get('voiced_fraction')} adapter={sa.get('pcs')}/{sa.get('voiced_fraction')}"
              + (f" ref={ref_name}" if ref_name else ""), flush=True)

    def agg(side):
        pcs = [r[side]["pcs"] for r in rows_ab if r[side].get("scored")]
        vf = [r[side]["voiced_fraction"] for r in rows_ab if r[side].get("scored")]
        return {"pcs_mean": round(float(np.mean(pcs)), 4) if pcs else None,
                "voiced_fraction_mean": round(float(np.mean(vf)), 3) if vf else None,
                "n_scored": len(pcs)}
    result["ab"] = {"dir": str(ab_dir), "n": len(caps), "seconds": args.ab_seconds,
                    "base": agg("base"), "adapter": agg("adapter"), "pairs": rows_ab}

    # 3. optional head-to-head: the other run's best adapter on the same base, on the test rows of the shared sources
    if h2h is not None:
        rows = h2h["rows"]
        same_rows = {r["clip_path"] for r in rows} == {r["clip_path"] for r in test_rows}
        this_song = adapter_song if same_rows else per_song_ce(adapter, tok, rows, tokens_dir, melody, chroma_dir)
        del adapter
        if DEVICE == "mps":
            torch.mps.empty_cache()
        other = build_model(args.model, args.targets, args.rank, args.alpha, str(h2h["other_ckpt"]))
        other_song = per_song_ce(other, tok, rows, tokens_dir, melody, chroma_dir)
        song_source = {r["song_sha256"]: source_of(r) for r in rows}
        result["headtohead"] = {"other_run": str(h2h["other_run"]), "other_ckpt": h2h["other_ckpt"].name,
                                "other_captions": str(h2h["other_captions"]),
                                "shared_sources": h2h["shared_sources"], "sources": source_counts(rows),
                                "n_clips": len(rows),
                                **headtohead_stats(this_song, other_song),
                                "per_source": per_source_headtohead(this_song, other_song, song_source)}
        print(json.dumps(result["headtohead"], indent=2), flush=True)

    # the JSON is written once, complete: an existing eval_<tag>.json has everything that was asked for
    out_json = run / f"eval_{args.tag}.json"
    out_json.write_text(json.dumps(result, indent=2))
    print(json.dumps({k: v for k, v in result.items() if k != "ab"} | {"ab_summary": {"base": result["ab"]["base"], "adapter": result["ab"]["adapter"]}}, indent=2), flush=True)
    print("SCALE_EVAL_DONE", flush=True)


if __name__ == "__main__":
    main()
