"""Evaluate a scaled MusicGen adapter against its own base (Stage 2).

Three parts, all song-level and rights-safe (no source audio leaves the machine;
only generated clips are written):

1. Per-SONG held-out test cross-entropy, base vs adapter, with a bootstrap 95%
   CI over songs. Clips are grouped by song_sha256, averaged within a song, and
   the CI is resampled over songs (the independent unit), not clips — so the
   interval is honest about how few songs the test split has.

2. A 16-clip A/B set into data/ab_<model>/: the same 16 seeded test captions
   generated by base and by the adapter with identical seeds, plus PCS +
   trackable-melody for every clip. The caption list is fixed across models
   (written once to data/ab_captions.json) so every model is heard on the same
   prompts.

3. A summary JSON with base/adapter test CE + CI, mean trackable-melody and PCS
   for base vs adapter, and the per-caption table.

Usage (from apps/ai-service):
  python -m scripts.scale_eval --run runs/qaraami_medium_r32 --model facebook/musicgen-medium \
     --captions ../../data/scale_captions.jsonl --tokens-dir ../../data/scale_tokens \
     --tag medium --n-ab 16
"""
from __future__ import annotations

import argparse
import json
import random
import time
from pathlib import Path

import numpy as np
import soundfile as sf
import torch
from transformers import AutoProcessor

from scripts.pcs import extract_f0, score_frames
from scripts.scale_train import DEVICE, build_model, delayed_labels, is_melody, load_split, token_path

REPO = Path(__file__).resolve().parents[3]
N_TEST_CLIPS = 128


def per_song_ce(model, tok, rows, tokens_dir) -> dict[str, float]:
    """Mean token CE per song_sha256 over its clips (eval mode)."""
    by_song: dict[str, list[float]] = {}
    model.eval()
    with torch.no_grad():
        for r in rows:
            text = tok(r["caption"], return_tensors="pt")
            labels = delayed_labels(token_path(tokens_dir, r))[None].to(DEVICE)
            loss = model(input_ids=text["input_ids"].to(DEVICE), attention_mask=text["attention_mask"].to(DEVICE), labels=labels).loss
            by_song.setdefault(r["song_sha256"], []).append(loss.item())
    if DEVICE == "mps":
        torch.mps.empty_cache()
    return {s: float(np.mean(v)) for s, v in by_song.items()}


def bootstrap_ci(values: list[float], n: int = 2000, seed: int = 0) -> tuple[float, float, float]:
    rng = random.Random(seed)
    arr = np.array(values)
    means = [float(np.mean([arr[rng.randrange(len(arr))] for _ in arr])) for _ in range(n)]
    return float(np.mean(arr)), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def score_clip(path: Path) -> dict:
    audio, sr = sf.read(path, dtype="float32")
    if audio.ndim > 1:
        audio = audio.mean(axis=1)
    f0, pd = extract_f0(audio, DEVICE, sr=sr)
    res = score_frames(f0, pd)
    if DEVICE == "mps":
        torch.mps.empty_cache()
    if res is None:
        return {"scored": False}
    return {"scored": True, "pcs": round(res.pcs, 4), "voiced_fraction": round(res.voiced_fraction, 3),
            "tuning_offset_cents": round(res.tuning_offset_cents, 1), "tonic": res.tonic_name}


@torch.no_grad()
def generate(model, processor, caption, seconds, seed, out_path) -> float:
    model.eval()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    torch.manual_seed(seed)
    inputs = processor(text=[caption], padding=True, return_tensors="pt").to(DEVICE)
    t0 = time.time()
    audio = model.generate(**inputs, do_sample=True, guidance_scale=3.0, max_new_tokens=int(seconds * 50))
    sr = model.config.audio_encoder.sampling_rate
    sf.write(out_path, audio[0].cpu().numpy().squeeze(), sr, subtype="PCM_16")
    if DEVICE == "mps":
        torch.mps.empty_cache()
    return time.time() - t0


def ab_captions(captions: Path, n: int, seed: int = 42) -> list[str]:
    cache = REPO / "data/ab_captions.json"
    if cache.exists():
        return json.loads(cache.read_text())[:n]
    test = load_split(captions, "test")
    uniq = sorted({r["caption"] for r in test})
    picked = random.Random(seed).sample(uniq, min(n, len(uniq)))
    cache.write_text(json.dumps(picked, indent=2))
    return picked


def find_best_ckpt(run: Path) -> Path:
    """Best checkpoint by val CE from loss.csv; fallback to the last ckpt dir."""
    import csv
    best_step, best_val = None, float("inf")
    lc = run / "loss.csv"
    if lc.exists():
        for row in csv.DictReader(open(lc)):
            if row.get("val_loss") and row["step"] != "0":
                v = float(row["val_loss"])
                if v < best_val:
                    best_val, best_step = v, int(row["step"])
    ckpts = sorted(run.glob("ckpt_step_*"), key=lambda p: int(p.name.split("_")[-1]))
    if best_step is not None:
        c = run / f"ckpt_step_{best_step:04d}"
        if c.exists():
            return c
    return ckpts[-1] if ckpts else run


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--model", required=True)
    ap.add_argument("--captions", required=True)
    ap.add_argument("--tokens-dir", required=True)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--rank", type=int, default=32)
    ap.add_argument("--alpha", type=int, default=64)
    ap.add_argument("--targets", nargs="*", default=["q_proj", "k_proj", "v_proj", "out_proj", "fc1", "fc2"])
    ap.add_argument("--n-ab", type=int, default=16)
    ap.add_argument("--ab-seconds", type=int, default=15)
    args = ap.parse_args()
    run = Path(args.run) if Path(args.run).is_absolute() else REPO / args.run
    captions = Path(args.captions)
    tokens_dir = Path(args.tokens_dir)
    processor = AutoProcessor.from_pretrained(args.model)
    tok = processor.tokenizer

    test = load_split(captions, "test")
    stride = max(1, len(test) // N_TEST_CLIPS)
    test_rows = sorted(test, key=lambda r: r["clip_path"])[::stride][:N_TEST_CLIPS]

    ckpt = find_best_ckpt(run)
    result = {"tag": args.tag, "model": args.model, "run": str(run), "best_ckpt": ckpt.name,
              "test_clips": len(test_rows), "test_songs": len({r["song_sha256"] for r in test_rows})}

    # 1. per-song CE, base then adapter
    base = build_model(args.model, args.targets, args.rank, args.alpha, None)
    base_song = per_song_ce(base, tok, test_rows, tokens_dir)
    del base
    if DEVICE == "mps":
        torch.mps.empty_cache()
    adapter = build_model(args.model, args.targets, args.rank, args.alpha, str(ckpt))
    adapter_song = per_song_ce(adapter, tok, test_rows, tokens_dir)

    songs = sorted(set(base_song) & set(adapter_song))
    b_mean, b_lo, b_hi = bootstrap_ci([base_song[s] for s in songs])
    a_mean, a_lo, a_hi = bootstrap_ci([adapter_song[s] for s in songs])
    deltas = [base_song[s] - adapter_song[s] for s in songs]
    d_mean, d_lo, d_hi = bootstrap_ci(deltas)
    result["per_song_ce"] = {
        "n_songs": len(songs),
        "base": {"mean": round(b_mean, 4), "ci95": [round(b_lo, 4), round(b_hi, 4)]},
        "adapter": {"mean": round(a_mean, 4), "ci95": [round(a_lo, 4), round(a_hi, 4)]},
        "improvement_base_minus_adapter": {"mean": round(d_mean, 4), "ci95": [round(d_lo, 4), round(d_hi, 4)],
                                            "significant": d_lo > 0},
    }
    print(json.dumps(result["per_song_ce"], indent=2), flush=True)

    # 2. A/B set (same captions/seeds for base and adapter)
    caps = ab_captions(captions, args.n_ab)
    ab_dir = REPO / f"data/ab_{args.tag}"
    ab_dir.mkdir(parents=True, exist_ok=True)
    (ab_dir / "CAPTIONS.txt").write_text("".join(f"pair{i:03d}: {c}\n" for i, c in enumerate(caps)))
    rows_ab = []
    for i, cap in enumerate(caps):
        seed = 42 + i
        bpath = ab_dir / f"pair{i:03d}_base.wav"
        apath = ab_dir / f"pair{i:03d}_adapter.wav"
        # base first (rebuild to disable adapter cleanly)
        adapter.set_adapter(adapter.active_adapters[0]) if hasattr(adapter, "active_adapters") else None
        with adapter.disable_adapter():
            generate(adapter, processor, cap, args.ab_seconds, seed, bpath)
        generate(adapter, processor, cap, args.ab_seconds, seed, apath)
        sb, sa = score_clip(bpath), score_clip(apath)
        rows_ab.append({"pair": i, "caption": cap, "base": sb, "adapter": sa})
        print(f"  ab {i+1}/{len(caps)} base pcs/voiced={sb.get('pcs')}/{sb.get('voiced_fraction')} adapter={sa.get('pcs')}/{sa.get('voiced_fraction')}", flush=True)

    def agg(side):
        pcs = [r[side]["pcs"] for r in rows_ab if r[side].get("scored")]
        vf = [r[side]["voiced_fraction"] for r in rows_ab if r[side].get("scored")]
        return {"pcs_mean": round(float(np.mean(pcs)), 4) if pcs else None,
                "voiced_fraction_mean": round(float(np.mean(vf)), 3) if vf else None,
                "n_scored": len(pcs)}
    result["ab"] = {"dir": str(ab_dir), "n": len(caps), "base": agg("base"), "adapter": agg("adapter"), "pairs": rows_ab}
    (run / f"eval_{args.tag}.json").write_text(json.dumps(result, indent=2))
    print(json.dumps({k: v for k, v in result.items() if k != "ab"} | {"ab_summary": {"base": result["ab"]["base"], "adapter": result["ab"]["adapter"]}}, indent=2), flush=True)
    print("SCALE_EVAL_DONE", flush=True)


if __name__ == "__main__":
    main()
