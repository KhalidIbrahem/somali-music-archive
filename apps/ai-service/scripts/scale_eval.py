"""Evaluate a scaled MusicGen adapter against its own base (Stage 2-4).

Three parts, all song-level and rights-safe (no source audio leaves the machine;
only generated clips are written):

1. Per-SONG held-out test cross-entropy, base vs adapter, with a bootstrap 95%
   CI over songs. Clips are grouped by song_sha256, averaged within a song, and
   the CI is resampled over songs (the independent unit), not clips — so the
   interval is honest about how few songs the test split has.

2. A 16-clip A/B set into data/ab_<tag>/: the same 16 seeded test captions
   generated by base and by the adapter with identical seeds, plus PCS +
   trackable-melody (voiced fraction) for every clip. The caption list is fixed
   across models (--ab-captions, written once from the test split when the file
   does not exist; --ab-rights restricts the seeding to rows with those rights)
   so every model is heard on the same prompts.

3. A summary JSON runs/<run>/eval_<tag>.json with base/adapter test CE + CI,
   mean trackable-melody and PCS for base vs adapter, the per-caption table,
   the test rows per source and the pinned scorer version (torchcrepe, PCS
   hop / confidence gate, sha256 of scripts/pcs.py).

Stage 3-4 extensions:
  * captions rows may carry "tokens_dir" / "chroma_dir" (repo-relative); they win
    over the CLI --tokens-dir / --chroma-dir, exactly as in scale_train
  * musicgen-melody: the per-song CE passes each clip's chroma as input_features,
    and every A/B pair conditions base AND adapter on the SAME reference chroma.
    The references come from --melody-refs <dir of wav> (default: the run
    captions' ahmed_oud test clips) spread over SONGS: pair i takes song i mod k
    (build_sets stems are <set>_<sha12>_segNNN, so the song is the stem without
    its segment), so sixteen pairs never sit on one song's sixteen segments; the
    reference file name and song are saved per pair
  * --headtohead-run <other run dir>: after the main eval, the other run's best
    adapter is loaded on the same base and scored on the SAME test rows, which
    are restricted to the sources both runs trained on (read from the other
    run's config.json -> captions), so a combined run is compared with an
    Ahmed-only run on the Ahmed songs, not on the Harvard songs it alone saw.
    The paired per-song difference (other − this, positive = this adapter has
    the lower CE) with a bootstrap 95% CI, overall and per source, lands in
    result["headtohead"]

Phase 3 extensions (eval_v2):
  * checkpoint kinds: a run's best checkpoint is a LoRA adapter dir
    (adapter_config.json, kind "lora") or a FULL-decoder checkpoint
    (decoder.safetensors + ckpt_meta.json, kind "full_decoder"). Both load
    through scale_train.load_checkpoint (looked up lazily; when this checkout
    has no such function a LoRA checkpoint takes the PEFT path as before and a
    full one is refused with a message).
    "base" for a full-decoder run is the pristine base model, loaded separately,
    since a full model has no disable_adapter(); its base-side clips are
    generated while the base is resident, then the tuned model replaces it
  * the per-song CE test rows are STRATIFIED by source (stratified_test_rows):
    an equal share of the 128-clip cap per source, strided within each source,
    with the share a small source cannot fill handed to the others, so a mixed
    run (isolated oud + ahmed_mix full mixes) is never scored on full mixes
    alone because their clip_paths sort first; result["test_sources"] records
    the composition. The head-to-head rows are picked the same way
  * --real-content (default: oud sep_oud): the content labels a row must carry
    (build_sets "content": oud | sep_oud | full_mix | voice | sep_vocal; a row
    without the field counts as oud when its source ends in "oud") to stand in
    the real MERT / tuning pool, to be the real side of a Turing pair, to seed
    the A/B caption list and to feed the extra generations. Full mixes are led
    by Somali vocals the models cannot sing, so a real pool or Turing set made
    of them would be trivially separable; "any" lifts the filter
  * --mert-real N (default 0, opt-in like --turing: it costs N extra 30 s
    generations per side): MERT-embedding distance. real = N held-out test
    clips of the run captions spread over songs, restricted to the --ab-rights
    tiers and --real-content, never Harvard rows unless the run itself trained
    on them (a research-only run); base = the A/B base clips plus extra base
    generations (data/ab_<tag>/mert_gen/genNNN_base.wav, caption j of the
    extended list, seed 42+j, the same rule as the A/B pairs) up to N, adapter
    likewise. result["mert"]: FAD(adapter, real), FAD(base, real),
    FAD(adapter, base), mean cosine to the real centroid, per-clip nearest-real
    cosine with a bootstrap 95% CI on the paired adapter-minus-base difference,
    closer_to_real (FAD to real: adapter below base) and real_sources. The
    embeddings of the real (consented) clips go to <ab dir>/mert_<tag>.npz,
    next to the generated clips (data/ab_*/ is git-ignored; the run dir, which
    the repo tracks, only ever gets the JSON)
  * result["tuning"]: tuning_offset_cents per clip for real, base and adapter
    (score_clip on the real clips too): mean, sd, fraction with |offset| >= 15
    cents, and the two-sample KS statistic real-vs-adapter and real-vs-base
  * --turing N: data/ab_turing_<tag>/pairNNN_real.wav (a held-out REAL clip from
    the run's CONSENTED test rows, copied) and pairNNN_model.wav (the adapter's
    output for that clip's caption, seed 42+i, same length); both sides of a
    pair are loudness-matched with pyloudnorm to the SAME integrated level,
    -14 LUFS or, when a side's peaks would clip there, the loudest level both
    reach without clipping (recorded per pair); CAPTIONS.txt and a README.txt
    that states the question and names the rights holders actually present
    (Ahmed Ilkacase, consented contributors). A Turing set is never built from
    harvard_* rows: with no consented test row the eval exits before any model loads
  * musicgen-melody generations (A/B pairs, mert_gen extras, the Turing model
    side) are conditioned on the SAME chroma the CE pass and recipe D's training
    use: the rows' chroma files (chroma_dir, e.g. data/sets/<set>/chroma_midi),
    passed to generate() as input_features; the Turing clip takes the real
    row's own chroma. --melody-refs <dir of wav> (processor chroma extracted
    from audio) is the fallback when the test rows have no chroma;
    result["melody_refs"]["chroma_source"] names which ("chroma_midi" /
    "chroma" = the chroma dir's name, or "audio"). generate() also applies
    patch_melody_generation: under transformers 4.57 musicgen-melody's
    generate() drops its text + chroma prefix at the first step (an empty
    DynamicCache already counts as "past"), so without it every melody clip is
    UNCONDITIONAL, whatever the caption or chroma (the CE / forward pass is
    unaffected). Any melody clip generated elsewhere without the fix is text-
    and chroma-blind
  * --out-dir / --ab-root move the eval JSON and the ab_* dirs (fixture runs
    write nothing under data/ or runs/); --mert-cache moves the MERT cache
  * generation is resumable and provenance-checked: every generated directory
    (ab_<tag>/ with its mert_gen/, ab_turing_<tag>/) carries GENERATED_BY.json
    naming the model, run, checkpoint, clip length, seed base and the caption
    list; a clip is reused only when it exists with the asked length AND the
    stamp agrees for its side (base clips depend on the model and captions,
    adapter and Turing clips also on the run and its best checkpoint). A side
    whose stamp differs, or clips without a stamp, are deleted and regenerated
    with a printed notice and result["generation"], so a re-eval after the best
    checkpoint moved never reports new numbers over old clips; --fresh
    regenerates everything
  * the A/B caption cache is seeded with at least 16 captions whatever --n-ab
    a probe eval asked, --n-ab 0 never writes one, and a cache shorter than
    --n-ab is refused (delete it or pass another --ab-captions)

Everything that can fail is checked before any model is loaded: an empty test
split, a run without a saved checkpoint (a half-written checkpoint dir,
scale_train.ckpt_kind None, counts as none and find_best_ckpt skips it), a
head-to-head run without one, on a different base model or without a shared
source, a rights filter that leaves no caption to seed from, a Turing set
without consented rows, a caption cache too short for --n-ab. The generation
plan (clips per side and their length) is printed before the models load. The
eval JSON is written only once everything asked for has been computed, so an
existing eval_<tag>.json is a complete one.

Generation is always batch 1.

Usage (from apps/ai-service):
  python -m scripts.scale_eval --run runs/qaraami_medium_r32 --model facebook/musicgen-medium \
     --captions ../../data/scale_captions.jsonl --tokens-dir ../../data/scale_tokens \
     --tag medium --n-ab 16
  python -m scripts.scale_eval --run runs/combined_large --model facebook/musicgen-large \
     --captions ../../data/sets/run_combined_large_captions.jsonl --tag combined_large \
     --n-ab 16 --ab-seconds 30 --ab-captions data/ab_captions_ahmed.json \
     --ab-rights ahmed_ilkacase_consented --headtohead-run runs/ahmed_only_large
  python -m scripts.scale_eval --run runs/ahmed_melody --model facebook/musicgen-melody \
     --captions ../../data/sets/ahmed_oud/captions.jsonl --tag ahmed_melody \
     --ab-captions data/ab_captions_ahmed.json --ab-rights ahmed_ilkacase_consented \
     --melody-refs data/sets/ahmed_oud/clips/test
  python -m scripts.scale_eval --run runs/qaraami_large --model facebook/musicgen-large \
     --captions ../../data/sets/run_qaraami_large_captions.jsonl --tag qaraami_large \
     --n-ab 16 --ab-seconds 30 --mert-real 64 --turing 16 \
     --ab-captions data/ab_captions_ahmed.json --ab-rights ahmed_ilkacase_consented
"""
