def inline_assets(page: str) -> str:
    def data_uri(rel: str) -> str:
        p = OUT / rel
        mime = "audio/mpeg" if p.suffix == ".mp3" else "image/png"
        return f"data:{mime};base64,{base64.b64encode(p.read_bytes()).decode('ascii')}"
    return re.sub(r'src="((?:audio|figures)/[^"]+)"', lambda mm: f'src="{data_uri(mm.group(1))}"', page)


# -------------------------------------------------------------------- main

def main() -> None:
    scale = {tag: load_scale(tag) for tag in ("medium", "large")}
    scale_captions = read_captions(DATA / "ab_large")
    best_step = int(scale["large"]["eval"]["best_ckpt"].split("_")[-1])
    prog_steps = PROGRESSION_STEPS + [best_step]

    clips: dict[str, Clip] = {}
    for tag in ("medium", "large"):
        pairs = {p["pair"]: p for p in scale[tag]["eval"]["ab"]["pairs"]}
        for i in SCALE_PAIRS:
            for side in ("base", "adapter"):
                sc = pairs[i][side]
                clips[f"{tag}_{i:03d}_{side}"] = Clip(
                    DATA / f"ab_{tag}" / f"pair{i:03d}_{side}.wav", f"{tag}_{i:03d}_{side}",
                    sc.get("pcs") if sc.get("scored") else None,
                    sc.get("voiced_fraction") if sc.get("scored") else None)
    small_captions, small_summary = {}, {}
    for key, info in SMALL.items():
        d = DATA / info["set"]
        small_captions[key] = read_captions(d)
        rows = {side: pcs_csv(name) for side, name in zip(("base", "adapter"), info["csv"])}
        for i in SMALL_PAIRS:
            for side, fname in (("base", "base"), ("adapter", "finetuned")):
                r = rows[side].get(i, {})
                clips[f"{key}_{i:03d}_{side}"] = Clip(
                    d / f"pair{i:03d}_{fname}.wav", f"{key}_{i:03d}_{side}",
                    num(r.get("pcs")), num(r.get("voiced_fraction")))
        summ = {}
        for side, name in zip(("base", "adapter"), info["csv"]):
            g = json.loads((DATA / "eval_pcs" / f"{name}.json").read_text())
            summ[f"pcs_{side}"] = g["pcs_mean"]
            summ[f"voiced_{side}"] = g["voiced_fraction_mean"]
        small_summary[key] = summ
    for s in prog_steps:
        clips[f"large_step{s:04d}"] = Clip(RUNS / "qaraami_large_r32/samples" / f"step_{s:04d}.wav", f"large_step{s:04d}")
    mel = json.loads((DATA / "ab_melody/melody_condition.json").read_text())
    melody_clips = []
    for c in sorted(mel["clips"], key=lambda c: -c["voiced_fraction"])[:N_MELODY]:
        clip = Clip(DATA / "ab_melody" / c["file"], f"melody_{c['i']:03d}", c["pcs"], c["voiced_fraction"])
        clips[clip.name] = clip
        melody_clips.append(clip)

    dpo = dpo_results()
    if dpo:
        passing = [s for s in dpo if dpo_ok(s["eval"])]
        top = (passing or dpo)[-1]
        for row in top["scores"]["pairs"][:N_DPO_PAIRS]:
            i = row["pair"]
            for side in ("base", "adapter"):
                src = top["ab_dir"] / f"pair{i:03d}_{side}.wav"
                if src.exists():
                    sc = row.get(side) or {}
                    clips[f'dpo_{top["tag"]}_{i:03d}_{side}'] = Clip(src, f'dpo_{top["tag"]}_{i:03d}_{side}', sc.get("pcs"), sc.get("voiced_fraction"))

    missing = [c.src for c in clips.values() if not c.src.exists()]
    if missing:
        sys.exit("missing source clips:\n  " + "\n  ".join(map(str, missing)))

    OUT.mkdir(parents=True, exist_ok=True)
    transcode(list(clips.values()))
    figure_scale_val({tag: scale[tag]["val_curve"] for tag in scale})
    FIGOUT.mkdir(exist_ok=True)
    for name in ("ft1_val_curves", "ft2_dropout_probe", "ft3_pcs_voiced", "ft7_scale_val_curves"):
        shutil.copy2(FIG / f"{name}.png", FIGOUT / f"{name}.png")

    ctx = {
        "scale": scale, "scale_captions": scale_captions, "clips": clips, "best_step": best_step,
        "prog_steps": prog_steps, "prog_caption": (RUNS / "qaraami_large_r32/sample_caption.txt").read_text().strip(),
        "melody_clips": melody_clips, "small_captions": small_captions, "small_summary": small_summary,
        "splits": split_counts(), "listening": listening_results(), "dpo": dpo,
    }
    page = build_html(ctx)
    (OUT / "index.html").write_text(page, encoding="utf-8")
    bundle = OUT / "QaraamiGen-demo.html"
    bundle.write_text(inline_assets(page), encoding="utf-8")

    mb = sum((AUDIO / f"{c.name}.mp3").stat().st_size for c in clips.values()) / 1e6
    print(f"{len(clips)} clips, {mb:.1f} MB of audio -> {OUT.relative_to(REPO)}/index.html")
    if ctx["listening"]:
        print("listening results:", ", ".join(f"{k}: {v['adapter']}/{v['n']}" for k, v in ctx["listening"].items()))
    else:
        print("no listening results in data/listening/ yet; page says the study is pending")
    print(f"single file: {bundle.relative_to(REPO)} ({bundle.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
