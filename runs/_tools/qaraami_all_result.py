"""Write runs/qaraami_all/RESULT.md from the run's own artifacts (loss.csv, config.json,
train.log, probe.log, eval_qaraami_all.json, the merged captions). No number is typed by hand."""
import csv, json, re, collections
from pathlib import Path
REPO = Path.home() / "Projects/somali-music-archive"
RUN = REPO / "runs/qaraami_all"
cfg = json.load(open(RUN / "config.json"))
rows = list(csv.DictReader(open(RUN / "loss.csv")))
vals = [(int(r["step"]), float(r["val_loss"])) for r in rows if r.get("val_loss")]
ckpts = {int(p.name.split("_")[-1]) for p in RUN.glob("ckpt_step_*") if (p / "adapter_config.json").exists()}
ck_vals = [(s, v) for s, v in vals if s in ckpts]
best_step, best_val = min(ck_vals, key=lambda t: (t[1], t[0])) if ck_vals else (None, None)
base_val = next((v for s, v in vals if s == 0), None)
last_step, last_val = ck_vals[-1] if ck_vals else (None, None)
# plateau: scale_train's early-stop criterion (patience 750 steps, min delta 0.002) applied post hoc —
# yes when the best val improved by <= 0.002 over the final 750 steps (the last three checkpoints)
MIN_DELTA, PATIENCE = 0.002, 750
ref = [v for s, v in ck_vals if last_step is not None and s <= last_step - PATIENCE]
plateau = bool(ref) and (min(ref) - best_val) <= MIN_DELTA
plateau_note = f"val at step {last_step - PATIENCE} minus best = {min(ref) - best_val:+.4f}" if ref else "fewer than 750 steps of checkpoints"

train_losses = [(int(r["step"]), float(r["train_loss"])) for r in rows if r.get("train_loss")]
spd = [float(r["sec_per_step"]) for r in rows if r.get("sec_per_step")]
mem = [float(r["mps_driver_gb"]) for r in rows if r.get("mps_driver_gb")]
tl = (RUN / "train.log").read_text()
m = re.search(r"functional_dropout_zeroed=(\d+) lora_sites=(\d+) trainable=(\S+ / \S+)", tl)
dropout, sites, trainable = (m.group(1), m.group(2), m.group(3)) if m else ("?", "?", "?")
probe = ""
pl = RUN / "probe.log"
if pl.exists():
    pm = re.search(r"\{[^{}]*\"peak_driver_gb\"[^{}]*\}", pl.read_text(), re.S)
    probe = pm.group(0) if pm else ""
cap_rows = [json.loads(l) for l in open(REPO / cfg["captions"]) ] if not Path(cfg["captions"]).is_absolute() else [json.loads(l) for l in open(cfg["captions"])]
hrs = collections.defaultdict(lambda: collections.defaultdict(float)); songs = collections.defaultdict(set)
for r in cap_rows:
    hrs[r["source"]][r["split"]] += r["seconds"] / 3600; songs[r["source"]].add(r["song_sha256"])
ev_path = RUN / "eval_qaraami_all.json"
ev = json.load(open(ev_path)) if ev_path.exists() else None
out = []
out.append("# qaraami_all — one musicgen-medium LoRA on the whole corpus\n")
out.append(f"Generated by `runs/_tools/qaraami_all_result.py` from the run's artifacts. Model `{cfg['model']}`, LoRA r{cfg['rank']} α{cfg['alpha']} on {cfg['targets']} ({sites} sites, {trainable}), lr {cfg['lr']}, {cfg['total_steps']} steps, batch {cfg['batch_size']} × grad-accum {cfg['grad_accum']}, {cfg['sample_seconds']} s samples, seed {cfg['seed']}, device {cfg['device']}, git `{cfg['git_commit'][:8]}`.\n")
out.append(f"Fixed-dropout harness: `functional_dropout_zeroed={dropout}`; step-0 val loss (base + init LoRA) {base_val}.\n")
if probe:
    out.append("Probe (20 smoke steps, 5 s samples):\n\n```json\n" + probe + "\n```\n")
out.append("## Data used (merged run captions, 30 s clips, song-level split, leakage check passed)\n")
out.append("| set | songs | train h | val h | test h | all h |\n| --- | --- | --- | --- | --- | --- |")
tot = collections.defaultdict(float)
for s in sorted(hrs):
    h = hrs[s]; a = sum(h.values())
    for k in ("train", "val", "test"): tot[k] += h[k]
    out.append(f"| `{s}` | {len(songs[s])} | {h['train']:.2f} | {h['val']:.2f} | {h['test']:.2f} | {a:.2f} |")
out.append(f"| **total** | {sum(len(v) for v in songs.values())} | {tot['train']:.2f} | {tot['val']:.2f} | {tot['test']:.2f} | {sum(tot.values()):.2f} |\n")
out.append(f"Train clips {cfg['train_clips']}, val clips used per validation {cfg['val_clips_used']} (strided over the merged val split). Clip-hours count every 30 s window; the oud collection (oud_ilkacase) is inside `ahmed_oud`.\n")
out.append("## Validation loss per checkpoint\n")
out.append("| step | val loss | Δ vs step 0 |\n| --- | --- | --- |")
for s, v in vals:
    mark = " **best**" if s == best_step else ""
    out.append(f"| {s}{' (no ckpt)' if s not in ckpts and s != 0 else ''} | {v:.4f}{mark} | {v - base_val:+.4f} |" if base_val is not None else f"| {s} | {v:.4f}{mark} | |")
out.append("")
out.append(f"- **Best checkpoint:** step {best_step} (val {best_val}); last checkpoint step {last_step} (val {last_val}).")
out.append(f"- **Plateau:** {'yes' if plateau else 'no'} — rule: scale_train's early-stop criterion applied post hoc (best val improved by no more than {MIN_DELTA} over the final {PATIENCE} steps; {plateau_note}).")
if train_losses:
    first = [v for s, v in train_losses if s <= 100]; last = [v for s, v in train_losses if s > train_losses[-1][0] - 250]
    out.append(f"- Train loss (10-step prints): first 100 steps mean {sum(first)/len(first):.3f}, last 250 steps mean {sum(last)/len(last):.3f}.")
if spd:
    out.append(f"- Speed {sum(spd)/len(spd):.1f} s/step mean (min {min(spd):.1f}, max {max(spd):.1f}); MPS driver memory max {max(mem):.1f} GB (cap {cfg.get('mem_cap_gb', 85)} GB).")
if ev:
    ce = ev["per_song_ce"]; ab = ev["ab"]
    out.append("\n## Held-out test (unseen songs), best checkpoint vs base\n")
    out.append(f"Evaluated checkpoint `{ev.get('best_ckpt')}`; {ev.get('test_clips')} test clips over {ev.get('test_songs')} songs" + (f", stratified by source {json.dumps(ev.get('test_sources'))}" if ev.get('test_sources') else "") + ".\n")
    out.append("```json\n" + json.dumps({"per_song_ce": ce}, indent=2) + "\n```\n")
    out.append("## Blind A/B set\n")
    out.append(f"- Path: `{Path(ab['dir']).relative_to(REPO)}/` — {ab['n']} pairs `pairNNN_{{base,adapter}}.wav`, 30 s, base = `facebook/musicgen-medium`, adapter = `{ev.get('best_ckpt')}`; captions `data/ab_captions.json` (the same 16 as `data/ab_medium/`), seed 42 + i on both sides.")
    out.append(f"- Base PCS {ab['base'].get('pcs_mean')} / voiced {ab['base'].get('voiced_fraction_mean')}; adapter PCS {ab['adapter'].get('pcs_mean')} / voiced {ab['adapter'].get('voiced_fraction_mean')} (n = {ab['adapter'].get('n_scored')}).")
    out.append("- Listen: `python apps/ai-service/scripts/ab_listen.py --open` → set `ab_qaraami_all` (blind test at `/test/ab_qaraami_all`, result lands in `data/listening/`).")
else:
    out.append("\n## Held-out test / A/B\n\nNot yet evaluated (`eval_qaraami_all.json` missing).")
(RUN / "RESULT.md").write_text("\n".join(out) + "\n")
print(f"wrote {RUN / 'RESULT.md'}: best step {best_step} val {best_val} plateau={plateau} eval={'yes' if ev else 'no'}")
