"""Serve the A/B listening sets on loopback so they can be heard side by side,
and run a blind paired comparison on any of them.

The listening test is the arbiter for every adapter in the programme, and the
sets already exist on disk: the same seeded captions generated by a base model
and by its adapter. The index page puts them next to each other with the scores
that were computed when they were generated. The test page (/test/<set>) hides
the scores and the file names, presents each pair as A and B in an order drawn
at random per pair, records which one the listener prefers, and writes the
result to data/listening/<set>_<listener>_<timestamp>.json with a Wilson 95%
interval on the adapter preference rate. build_demo_page.py reads those files.

Sets picked up when present:
  data/ab_<tag>/               pairNNN_{base,adapter}.wav + runs/qaraami_<tag>_r32/eval_<tag>.json
  data/oud_ab_listening/       pairNNN_{base,finetuned}.wav + data/eval_pcs/oud_{base,lora500}.csv
  data/harvard_ab_listening/   pairNNN_{base,finetuned}.wav + data/eval_pcs/harvard_{base,lora1500}.csv
  data/ab_melody/              melodyNNN_base.wav + melody_condition.json

Binds 127.0.0.1 only. Serves nothing but these generated clips; source audio is
never on this page. Stdlib only.

Usage (from the repo root):
  python apps/ai-service/scripts/ab_listen.py            # http://127.0.0.1:8777
  python apps/ai-service/scripts/ab_listen.py --open     # and open it in the browser
"""
