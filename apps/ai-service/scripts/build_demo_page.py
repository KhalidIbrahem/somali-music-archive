def figure_scale_val(curves: dict[str, tuple[list[int], list[float]]]) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({"figure.dpi": 150, "font.size": 9, "axes.spines.top": False,
                         "axes.spines.right": False, "font.family": "sans-serif"})
    colors = {"medium": "#2f6fb0", "large": "#c8843a"}   # validated pair, light surface
    fig, ax = plt.subplots(figsize=(7.4, 3.6))
    xmax = max(s[-1] for s, _ in curves.values())
    for tag, (steps, vals) in curves.items():
        ax.hlines(vals[0], -60, xmax, color=colors[tag], lw=1, ls=(0, (1, 3)), alpha=0.8)
        ax.plot(steps, vals, color=colors[tag], lw=2, marker="o", ms=4,
                solid_joinstyle="round", solid_capstyle="round", label=f"MusicGen-{tag}, LoRA r32")
        ax.text(xmax + 60, vals[0], f"base {vals[0]:.4f}", va="center", fontsize=7.5, color="#666")
        ax.text(xmax + 60, vals[-1], f"{vals[-1]:.4f}", va="center", fontsize=8, color="#222")
    ax.set_xlim(-60, xmax + 520)
    ax.set_xlabel("optimizer step")
    ax.set_ylabel("validation token cross-entropy (nats)")
    ax.set_title("Validation cross-entropy per checkpoint; dotted lines are each model's base", fontsize=9)
    ax.grid(axis="y", color="#e6e6e6", lw=0.8)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, fontsize=8, loc="center right")
    fig.tight_layout()
    fig.savefig(FIG / "ft7_scale_val_curves.png")
    fig.savefig(FIG / "ft7_scale_val_curves.svg")
    plt.close(fig)


# ------------------------------------------------------------------- html

def esc(s: object) -> str:
    return html.escape(str(s))


def f3(x: float | None) -> str:
    return "–" if x is None else f"{x:.3f}"


def f4(x: float) -> str:
    return f"{x:.4f}"


def player(c: Clip | None, scored: bool = True) -> str:
    if c is None:
        return "<td>–</td>"
    s = ""
    if scored:
        if c.pcs is not None or c.voiced is not None:
            s = f'<div class="score">PCS {f3(c.pcs)} · voiced {f3(c.voiced)}</div>'
        else:
            s = '<div class="score">too little pitched content to score</div>'
    return f'<td class="clip"><audio controls preload="metadata" src="{esc(c.rel)}"></audio>{s}</td>'


def delta(a: float, b: float) -> str:
    return f"{b - a:+.3f}"


