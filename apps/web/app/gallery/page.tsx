/**
 * /gallery — every clip the releasable models generated, not a selection.
 * Server-rendered from lib/gallery-clips.json (written by
 * `apps/ai-service/scripts/clip_chooser.py gallery`); audio loads only when
 * played. AI model output only: the rights gate refuses any file whose model
 * card is not `releasable`, and no source recording is ever listed here.
 */

import type { Metadata } from 'next';
import { SiteHeader } from '@/components/SiteHeader';
import { SiteFooter } from '@/components/SiteFooter';
import gallery from '@/lib/gallery-clips.json';

export const metadata: Metadata = {
  alternates: { canonical: '/gallery' },
  title: 'Somali Music AI Gallery — AI-Generated Somali Songs & Audio | QaraamiGenAI',
  description:
    'Explore the full gallery of AI-generated Somali songs, vocal melodies, and Kaban performances produced by QaraamiGenAI models.',
  keywords: [
    'somali music ai',
    'Somali AI songs',
    'AI Somali music gallery',
    'Somali oud audio AI',
    'qaraami ai gallery',
  ],
};

interface GalleryClip {
  readonly id: string;
  readonly file: string;
  readonly title: string;
  readonly model: string;
  readonly adapter: string;
  readonly checkpoint: string;
  readonly prompt: string;
  readonly durationSec: number;
  readonly vocals: boolean;
  readonly pcs?: number;
  readonly voiced?: number;
  readonly bandSnrDb?: number;
  readonly autoPick?: boolean;
}

interface GalleryGroup {
  readonly title: string;
  readonly note: string;
  readonly sections: readonly { readonly title: string; readonly clips: readonly GalleryClip[] }[];
}

const GROUPS: readonly GalleryGroup[] = (gallery as { groups: readonly GalleryGroup[] }).groups;
const TOTAL = GROUPS.reduce((n, g) => n + g.sections.reduce((m, s) => m + s.clips.length, 0), 0);

function Clip({ c }: { c: GalleryClip }): React.JSX.Element {
  return (
    <li className="rounded-[4px] border border-hairline bg-chrome-1 px-4 py-3">
      <div className="flex flex-wrap items-center gap-x-3 gap-y-1">
        <h4 className="font-display text-base text-hi">{c.title}</h4>
        <span className="numeric rounded-full border border-hairline px-2 py-0.5 text-[10px] tracking-[0.14em] text-accent-state uppercase">
          AI output
        </span>
        {c.autoPick && (
          <span className="numeric rounded-full border border-hairline px-2 py-0.5 text-[10px] tracking-[0.14em] text-accent-live uppercase">
            auto pick
          </span>
        )}
      </div>
      <audio controls preload="none" src={c.file} className="mt-2 w-full">
        Your browser cannot play this audio.
      </audio>
      <p className="numeric mt-1 text-[11px] text-low">
        {c.durationSec} s{c.pcs !== undefined && ` · PCS ${c.pcs.toFixed(3)}`}
        {c.voiced !== undefined && ` · voiced ${Math.round(c.voiced * 100)} %`}
        {c.bandSnrDb !== undefined && ` · band SNR ${c.bandSnrDb.toFixed(1)} dB`}
        {` · ${c.checkpoint}`}
      </p>
    </li>
  );
}

export default function GalleryPage(): React.JSX.Element {
  return (
    <div className="flex min-h-screen flex-col bg-page font-body text-hi">
      <SiteHeader active="Gallery" />
      <main className="mx-auto w-full max-w-4xl flex-1 px-4 pt-10 pb-32 sm:px-6">
        <header className="mb-8">
          <p className="numeric text-xs tracking-[0.24em] text-accent-state uppercase">
            Everything the models made
          </p>
          <h1 className="mt-3 font-display text-3xl text-hi sm:text-4xl">Gallery</h1>
          <p className="mt-3 max-w-2xl text-sm leading-relaxed text-mid sm:text-base">
            All {TOTAL} clips generated by the project&apos;s releasable models, unselected and
            unedited, good and bad. Every clip is AI model output, not a recording; no source
            recording is served on this site. Models trained on archival collections with
            research-only rights are not included.
          </p>
          <p className="mt-3 max-w-2xl text-[13px] leading-relaxed text-low">
            PCS: share of pitched frames within ±50 cents of the fitted pentatonic scale. Voiced:
            share of frames with a confident pitch. Band SNR: signal-to-noise in the melody band.
            &ldquo;Auto pick&rdquo; marks the clip an automatic score ranked first among the 32
            generations for its prompt.
          </p>
        </header>
        {GROUPS.map((g, gi) => (
          <section key={g.title} className="mb-10">
            <h2 className="font-display text-2xl text-hi">{g.title}</h2>
            <p className="mt-2 max-w-2xl text-[13px] leading-relaxed text-mid">{g.note}</p>
            {g.sections.map((s, si) => (
              <details
                key={`${g.title}-${s.title}`}
                open={gi === 0 && si === 0}
                className="mt-4 border-t border-hairline pt-3"
              >
                <summary className="cursor-pointer text-sm text-hi">
                  {s.title || 'All clips'}{' '}
                  <span className="numeric text-low">· {s.clips.length} clips</span>
                </summary>
                <ul className="mt-3 grid gap-3 sm:grid-cols-2">
                  {s.clips.map((c) => (
                    <Clip key={c.id} c={c} />
                  ))}
                </ul>
              </details>
            ))}
          </section>
        ))}
      </main>
      <SiteFooter />
    </div>
  );
}
